import { Rating } from '@/components/ui/rating'
import { getCourseOutline, getCourseReviews, listCourseSlugs } from '@/lib/data'
import { formatDate, formatDuration, plural } from '@/lib/format'

/*
  DYNAMIC ROUTE /courses/[slug] (Days 11–13), with today's types:
  - PageProps<'/courses/[slug]'> is generated by Next.js from the folder
    name, so `params` is typed Promise<{ slug: string }>, and a typo like
    params.slg is a compile error.
  - params is a Promise in current Next.js: we await it.
  - generateStaticParams lists every course slug, so all eight course pages
    are prerendered as static HTML at build time. An unknown slug renders
    on demand and hits notFound() → not-found.tsx.
*/

export async function generateStaticParams() {
  const slugs = await listCourseSlugs()
  return slugs.map((slug) => ({ slug }))
}

export async function generateMetadata({ params }: PageProps<'/courses/[slug]'>): Promise<Metadata> {
  const { slug } = await params
  const outline = await getCourseOutline(slug)
  if (!outline) return { title: 'Course not found' }
  return { title: outline.title, description: outline.subtitle }
}

